// Sync Homepage Navigation Header with Logged-In User state
function syncHeaderUserState() {
    const activeUser = JSON.parse(localStorage.getItem('active_user'));
    if (activeUser) {
        const ctaBtns = document.querySelectorAll('#headerCtaBtn, a[href="login-register.html"]');
        ctaBtns.forEach(btn => {
            // Hide the button or point to my-account.html, never admin.html for public safety
            btn.href = activeUser.role === 'admin' ? 'admin.html' : 'my-account.html';
            const span = btn.querySelector('span');
            
            // If admin is logged in, show "My Account" instead of "Admin Panel" to hide admin presence from guests
            const labelText = activeUser.role === 'admin' ? 'මගේ ගිණුම (My Account)' : 'මගේ ගිණුම (My Account)';
            if (span) {
                span.textContent = labelText;
            } else {
                btn.textContent = labelText;
            }
        });
    }
}

// Sync Course Catalog with Admin Panel customizations (localStorage)
function syncCourseCatalogDOM() {
    syncHeaderUserState();
    const adminCourses = JSON.parse(localStorage.getItem('hapanamy_courses_list'));
    if (!adminCourses) return;

    adminCourses.forEach(c => {
        // 1. Update in-memory courseData object so that details modals render the new details
        if (courseData[c.id]) {
            courseData[c.id].title = c.title;
            courseData[c.id].category = c.category;
            courseData[c.id].originalPrice = 'රු. ' + c.price.toLocaleString();
            courseData[c.id].currentPrice = 'රු. ' + c.discount.toLocaleString();
            courseData[c.id].banner = c.image;
            courseData[c.id].desc = c.desc || courseData[c.id].desc;
            courseData[c.id].syllabus = c.syllabus && c.syllabus.length > 0 ? c.syllabus : courseData[c.id].syllabus;
        }

        // 2. Find and update corresponding product card elements in the DOM
        const categoryMap = {
            'Social Media': 'social-media',
            'Trading Course': 'trading',
            'AI & Tech': 'ai-tech',
            'E-Book': 'ebooks'
        };

        const cards = document.querySelectorAll('.course-card');
        cards.forEach(card => {
            const btn = card.querySelector('.btn-card-action');
            if (btn && btn.getAttribute('onclick') && btn.getAttribute('onclick').includes(c.id)) {
                // Update card image banner
                const img = card.querySelector('.card-img');
                if (img) img.src = c.image;

                // Update category badge tag
                const cat = card.querySelector('.badge-category');
                if (cat) cat.textContent = c.category;

                // Update course Title text
                const title = card.querySelector('.card-title');
                if (title) title.textContent = c.title;

                // Update regular and discount prices
                const priceOrig = card.querySelector('.price-original');
                const priceCurr = card.querySelector('.price-current');
                if (priceOrig) priceOrig.textContent = 'රු. ' + c.price.toLocaleString();
                if (priceCurr) priceCurr.textContent = 'රු. ' + c.discount.toLocaleString();

                // Update commission badge
                const commVal = card.querySelector('.badge-value');
                if (commVal) {
                    const commissionAmount = Math.round(c.discount * 0.15);
                    commVal.textContent = 'රු. ' + commissionAmount.toLocaleString() + '.00';
                }

                // Store status and map category dynamically
                card.dataset.status = c.status;
                if (categoryMap[c.category]) {
                    card.dataset.category = categoryMap[c.category];
                }

                // If product status is Inactive, hide the card completely from homepage catalog!
                if (c.status === 'Inactive') {
                    card.style.setProperty('display', 'none', 'important');
                } else {
                    card.style.display = 'flex';
                }
            }
        });
    });
}
