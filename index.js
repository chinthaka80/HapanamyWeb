// Course search & filter tabs logic
function initCourseFilter() {
    const searchInput = document.getElementById('courseSearchInput');
    const filterButtons = document.querySelectorAll('.filter-btn');
    const courseCards = document.querySelectorAll('.course-card');

    function filterCourses() {
        const query = searchInput.value.toLowerCase().trim();
        const selectedFilter = document.querySelector('.filter-btn.active').dataset.category;

        courseCards.forEach(card => {
            const cardTitle = card.dataset.title || '';
            const cardCategory = card.dataset.category || '';
            const cardStatus = card.dataset.status || 'Active';
            
            const matchesSearch = cardTitle.includes(query) || card.textContent.toLowerCase().includes(query);
            const matchesCategory = selectedFilter === 'all' || cardCategory === selectedFilter;

            if (matchesSearch && matchesCategory && cardStatus !== 'Inactive') {
                card.style.display = 'flex';
            } else {
                card.style.display = 'none';
            }
        });
    }

    if (searchInput) {
        searchInput.addEventListener('keyup', filterCourses);
    }

    filterButtons.forEach(btn => {
        btn.addEventListener('click', () => {
            filterButtons.forEach(b => b.classList.remove('active'));
            btn.classList.add('active');
            filterCourses();
        });
    });
}

// Count Up Statistics Animation
function initStatsCounter() {
    const stats = document.querySelectorAll('.stat-number, .stat-number-pct, .stat-number-rs');
    
    const countUp = (element) => {
        const target = parseInt(element.getAttribute('data-target'), 10);
        let count = 0;
        const duration = 2000; // 2 seconds
        const stepTime = Math.max(Math.floor(duration / target), 15);
        
        const isPct = element.classList.contains('stat-number-pct');
        const isRs = element.classList.contains('stat-number-rs');

        const timer = setInterval(() => {
            if (target <= 100) {
                count += 1;
            } else if (target <= 10000) {
                count += Math.floor(target / 100);
            } else {
                count += Math.floor(target / 50);
            }

            if (count >= target) {
                count = target;
                clearInterval(timer);
            }
            
            if (isRs) {
                element.textContent = 'රු. ' + count.toLocaleString();
            } else if (isPct) {
                element.textContent = count + '%';
            } else {
                element.textContent = count.toLocaleString() + '+';
            }
        }, stepTime);
    };

    // IntersectionObserver to animate numbers only when visible
    const observer = new IntersectionObserver((entries, observer) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                countUp(entry.target);
                observer.unobserve(entry.target);
            }
        });
    }, { threshold: 0.5 });

    stats.forEach(stat => {
        observer.observe(stat);
    });
}

