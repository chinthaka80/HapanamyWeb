// --- Hapanamy.lk Shopping Cart System Logic ---
let cart = JSON.parse(localStorage.getItem('hapanamy_cart')) || [];

function toggleCartDrawer(isOpen) {
    const drawer = document.getElementById('cartDrawer');
    if (!drawer) return;
    drawer.style.right = isOpen ? '0px' : '-400px';
}

function addToCart(id, title, price) {
    // Check if course already added
    const exists = cart.some(item => item.id === id);
    if (exists) {
        showToast('⚠️ <strong>දැනටමත් ඇතුළත් කර ඇත!</strong> මෙම නිෂ්පාදනය දැනටමත් කරත්තයේ පවතී.');
        toggleCartDrawer(true);
        return;
    }

    cart.push({ id, title, price });
    localStorage.setItem('hapanamy_cart', JSON.stringify(cart));
    
    updateCartUI();
    toggleCartDrawer(true);
    
    const currentLang = localStorage.getItem('language') || 'si';
    showToast(currentLang === 'si' 
        ? `🛒 <strong>කරත්තයට එක් කරන ලදී!</strong> '${title}' සාර්ථකව ඇතුළත් කරන ලදී.`
        : `🛒 <strong>Added to Cart!</strong> '${title}' successfully added.`
    );
}

function removeFromCart(index) {
    const title = cart[index].title;
    cart.splice(index, 1);
    localStorage.setItem('hapanamy_cart', JSON.stringify(cart));
    updateCartUI();
    
    const currentLang = localStorage.getItem('language') || 'si';
    showToast(currentLang === 'si'
        ? `🗑️ <strong>ඉවත් කරන ලදී!</strong> '${title}' කරත්තයෙන් ඉවත් කරන ලදී.`
        : `🗑️ <strong>Removed!</strong> '${title}' removed from cart.`
    );
}

function updateCartUI() {
    const countEl = document.getElementById('floatingCartCount');
    const listEl = document.getElementById('cartDrawerItemsList');
    const totalEl = document.getElementById('cartDrawerTotalVal');
    
    if (!countEl || !listEl || !totalEl) return;

    countEl.textContent = cart.length;
    listEl.innerHTML = '';
    
    let total = 0;
    
    if (cart.length === 0) {
        listEl.innerHTML = `<div style="text-align: center; color: var(--text-muted); margin-top: 40px; font-size: 13.5px;">කරත්තය හිස්ව පවතී (Cart is empty).</div>`;
        totalEl.textContent = 'රු. 0.00';
        return;
    }

    cart.forEach((item, index) => {
        const row = document.createElement('div');
        row.className = 'cart-item-row';
        row.innerHTML = `
            <div>
                <div class="cart-item-title">${item.title}</div>
                <div class="cart-item-price">රු. ${item.price.toLocaleString()}</div>
            </div>
            <button onclick="removeFromCart(${index})" class="btn-remove-cart">&times; Remove</button>
        `;
        listEl.appendChild(row);
        total += item.price;
    });

    totalEl.textContent = 'රු. ' + total.toLocaleString();
}

function proceedToCheckout() {
    if (cart.length === 0) {
        showToast('⚠️ <strong>කරත්තය හිස්!</strong> කරුණාකර ප්‍රථමයෙන් පාඨමාලාවක් එක් කරන්න.');
        return;
    }
    window.location.href = 'checkout.html';
}

